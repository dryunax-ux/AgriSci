export function getGrade9ScienceRichNote(title: string): RichNote | null {
  const selected = packs.find((item) => item.match.test(title));
  if (!selected) return null;
  return {
    overview: selected.overview,
    explanations: selected.ideas,
    procedure: selected.process,
    safety: selected.safety,
    summary: selected.summary,
    misconceptions: [
      {
        claim: `${title} can be explained accurately without measurements, models or evidence.`,
        correction: "Scientific explanations should use appropriate observations, measurements and models.",
      },
      {
        claim: "A diagram or model shows every feature exactly as it exists in reality.",
        correction: "Models simplify selected features and should be interpreted with their limitations.",
      },
    ],
    oralQuestions: selected.questions,
    diagramPrompt: selected.diagram,
  };
}
